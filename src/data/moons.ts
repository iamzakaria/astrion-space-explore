export const MOON_BY_SLUG: Record<string, Moon> = Object.fromEntries(
  MOONS.map((m) => [m.slug, m]),
);

export function getMoon(slug: string): Moon | undefined {
  return MOON_BY_SLUG[slug];
}

export function moonsForPlanet(planetSlug: string): Moon[] {
  return MOONS.filter((m) => m.planetSlug === planetSlug).sort(
    (a, b) => a.semiMajorKm - b.semiMajorKm,
  );
}


export const NEBULA_BY_SLUG: Record<string, Nebula> = Object.fromEntries(
  NEBULAE.map((n) => [n.slug, n]),
);

export function getNebula(slug: string): Nebula | undefined {
  return NEBULA_BY_SLUG[slug];
}

export function nebulaeForStar(slug: string): Nebula[] {
  return NEBULAE.filter((n) => n.illuminatorSlug === slug);
}

export function nebulaeInConstellation(slug: string): Nebula[] {
  return NEBULAE.filter((n) => n.constellation === slug).sort(
    (a, b) => a.distanceLy - b.distanceLy,
  );
}

export function kindCountNebulae(kind: NebulaKind): number {
  return NEBULAE.filter((n) => n.kind === kind).length;
}


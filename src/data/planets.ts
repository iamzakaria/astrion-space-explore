export const PLANET_BY_SLUG: Record<string, Planet> = Object.fromEntries(
  PLANETS.map((p) => [p.slug, p]),
);

export function getPlanet(slug: string): Planet | undefined {
  return PLANET_BY_SLUG[slug];
}

export function planetsForStar(starSlug: string): Planet[] {
  return PLANETS.filter((p) => p.hostSlug === starSlug).sort((a, b) => a.au - b.au);
}

export function systemOf(planet: Planet): Planet[] {
  return PLANETS.filter((p) => {
    if (planet.hostSlug) return p.hostSlug === planet.hostSlug;
    return p.hostName === planet.hostName;
  }).sort((a, b) => a.au - b.au);
}

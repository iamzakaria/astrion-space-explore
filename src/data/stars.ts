export const STAR_BY_SLUG: Record<string, Star> = Object.fromEntries(
  STARS.map((s) => [s.slug, s]),
);

export function getStar(slug: string): Star | undefined {
  return STAR_BY_SLUG[slug];
}

export function starsInConstellation(slug: string): Star[] {
  return STARS.filter((s) => s.constellation === slug).sort(
    (a, b) => a.apparentMag - b.apparentMag,
  );
}
